package bioflix.catalog.grpc;

import bioflix.catalog.entity.Hall;
import bioflix.catalog.entity.Movie;
import bioflix.catalog.entity.Showtime;
import bioflix.catalog.exception.NotFoundException;
import bioflix.catalog.service.HallService;
import bioflix.catalog.service.MovieService;
import bioflix.catalog.service.ShowtimeService;
import bioflix.grpc.catalog.CatalogServiceGrpc;
import bioflix.grpc.catalog.GetShowtimeRequest;
import bioflix.grpc.catalog.ShowtimeDetails;
import io.grpc.Status;
import io.grpc.stub.StreamObserver;
import org.springframework.grpc.server.service.GrpcService;

/**
 * gRPC endpoint used by booking-service (see src/main/proto/catalog.proto).
 * Classes in bioflix.grpc.catalog are generated by Maven – run "mvn compile" once
 * (or "Reload Maven project" + "Generate Sources" in IntelliJ).
 */
@GrpcService
public class CatalogGrpcService extends CatalogServiceGrpc.CatalogServiceImplBase {

    private final ShowtimeService showtimeService;
    private final MovieService movieService;
    private final HallService hallService;

    public CatalogGrpcService(ShowtimeService showtimeService, MovieService movieService, HallService hallService) {
        this.showtimeService = showtimeService;
        this.movieService = movieService;
        this.hallService = hallService;
    }

    @Override
    public void getShowtime(GetShowtimeRequest request, StreamObserver<ShowtimeDetails> responseObserver) {
        try {
            Showtime showtime = showtimeService.findOrThrow(request.getShowtimeId());
            Movie movie = movieService.findOrThrow(showtime.getMovieId());
            Hall hall = hallService.findOrThrow(showtime.getHallId());

            ShowtimeDetails reply = ShowtimeDetails.newBuilder()
                    .setShowtimeId(showtime.getId())
                    .setMovieId(movie.getId())
                    .setMovieTitle(movie.getTitle())
                    .setHallId(hall.getId())
                    .setHallName(hall.getName())
                    .setStartTimeEpochSeconds(showtime.getStartTime().getEpochSecond())
                    .setPriceMinor(showtime.getPriceMinor())
                    .setCurrency(showtime.getCurrency())
                    .setRows(hall.getRows())
                    .setSeatsPerRow(hall.getSeatsPerRow())
                    .build();

            responseObserver.onNext(reply);
            responseObserver.onCompleted();
        } catch (NotFoundException ex) {
            responseObserver.onError(Status.NOT_FOUND.withDescription(ex.getMessage()).asRuntimeException());
        } catch (RuntimeException ex) {
            responseObserver.onError(Status.INTERNAL.withDescription(ex.getMessage()).asRuntimeException());
        }
    }
}
